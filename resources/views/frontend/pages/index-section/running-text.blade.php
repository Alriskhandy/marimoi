<script>
    (function() {
        const section = document.querySelector('.running-text');
        const container = document.querySelector('.running-content');
        if (!container || !section) return;

        // Duplicate content for seamless loop
        function ensureDuplicate() {
            const originalContent = container.innerHTML;
            container.innerHTML = originalContent + originalContent;
        }

        // Wait for images to load
        function waitForImages() {
            const imgs = Array.from(container.querySelectorAll('img'));
            if (imgs.length === 0) return Promise.resolve();

            const promises = imgs.map(img => new Promise(resolve => {
                if (img.complete && img.naturalWidth !== 0) return resolve();
                img.addEventListener('load', resolve, {
                    once: true
                });
                img.addEventListener('error', resolve, {
                    once: true
                });
            }));
            return Promise.all(promises);
        }

        let oneSetWidth = 0;
        let rafId = null;
        let lastTime = 0;
        let pos = 0;
        const speed = 80; // pixels per second

        function measure() {
            const total = container.scrollWidth;
            oneSetWidth = total / 2;
            if (!isFinite(oneSetWidth) || oneSetWidth <= 0) {
                oneSetWidth = 0;
            }
        }

        function tick(now) {
            if (!lastTime) lastTime = now;
            const dt = now - lastTime;
            lastTime = now;

            if (oneSetWidth > 0) {
                pos += (speed * dt) / 1000;

                // Reset position seamlessly when we've moved one full set width
                if (pos >= oneSetWidth) {
                    pos = pos - oneSetWidth;
                }

                container.style.transform = `translateX(${-pos}px)`;
            }

            rafId = requestAnimationFrame(tick);
        }

        function start() {
            if (rafId) cancelAnimationFrame(rafId);
            lastTime = 0;
            pos = 0;
            rafId = requestAnimationFrame(tick);
        }

        // Handle resize
        let resizeTimer = null;
        window.addEventListener('resize', () => {
            if (resizeTimer) clearTimeout(resizeTimer);
            resizeTimer = setTimeout(() => {
                measure();
            }, 120);
        }, {
            passive: true
        });

        // Initialize
        waitForImages().then(() => {
            ensureDuplicate();
            requestAnimationFrame(() => {
                measure();
                start();
            });
        });
    })();
</script>
